/* -----------------------------------------------------------------------------
   Which glyph a sidebar row gets. Keys are nav keys, not routes — see
   DashboardShell's navItems and backend/utils/navBadges.js.
   -------------------------------------------------------------------------- */
const ICON_MAP = {
  overview: GridIcon,
  notifications: BellIcon,
  // A clock, not a second bell. The bell is "something is wrong right now"; the Reminder
  // Centre is "this is due, and here is when" — two rows next to each other in the sidebar,
  // and a shopkeeper must be able to tell them apart without reading either label.
  reminders: ClockIcon,
  // The same bolt the dashboard's advice panel already wears, so the row down the rail
  // and the panel on the Overview are visibly the same feature. `usage` shares the glyph
  // and never collides: that one is a platform-admin screen no shopkeeper can reach.
  advice: ZapIcon,
  inventory: BoxIcon,
  // The bare rupee, and deliberately not the wallet (`expenses`) or the shield
  // (`backup`): this screen is about money the shop already owns and is about to lose
  // hold of, not about money going out and not about protection.
  savings: RupeeIcon,
  billing: ReceiptIcon,
  estimates: EstimateIcon,
  recurring: RepeatIcon,
  counters: CounterIcon,
  tables: TableIcon,
  kitchen: KitchenIcon,
  appointments: CalendarIcon,
  jobs: ToolboxIcon,
  memberships: MembershipIcon,
  khata: LedgerIcon,
  orders: OrdersIcon,
  catalog: ListIcon,
  suppliers: TruckIcon,
  supplierLedger: NotepadIcon,
  purchaseOrders: ClipboardIcon,
  // Goods going back the other way.
  purchaseReturns: UndoIcon,
  // Goods coming back from a CUSTOMER, and the money that goes back with them.
  creditNotes: HandCoinsIcon,
  // The other direction of the whole relationship: goods leaving this shop for another
  // shop. Deliberately NOT the truck (that is `suppliers`, the people this shop buys
  // FROM) — a wholesaler reading his own sidebar must not see the same glyph twice and
  // have to work out which one is his.
  supply: PackageIcon,
  loyalty: StarIcon,
  offers: OfferIcon,
  stores: StoreIcon,
  centralInventory: WarehouseIcon,
  transfers: SwapIcon,
  staff: UsersIcon,
  myWork: TaskDoneIcon,
  expenses: WalletIcon,
  daybook: BookIcon,
  accounting: ScalesIcon,
  backup: ShieldIcon,
  labels: BarcodeIcon,
  reports: BarChartIcon,
  analytics: PieChartIcon,
  plan: CreditCardIcon,
  // A gift, not a megaphone: the seller screen is about what the shopkeeper RECEIVES for an
  // invitation, and the shop's own advertising already owns the megaphone (`campaigns`).
  refer: GiftIcon,
  dukaans: ShopIcon,
  // The headset, matching the seller-side support button exactly. It is the glyph every
  // Indian app puts on the row that reaches a human, and the two ends of the same
  // conversation should not wear different icons.
  support: HeadsetIcon,
  users: UsersIcon,
  settings: SettingsIcon,
  // Platform admin sections.
  modules: SlidersIcon,
  advisories: ZapIcon,
  staffAccess: KeyIcon,
  plans: CreditCardIcon,
  platform: SettingsIcon,
  audit: AuditIcon,
  revenue: RevenueIcon,
  usage: ZapIcon,
  growth: TargetIcon,
  // The admin half of the same programme the seller's `refer` row opens.
  referrals: GiftIcon,
  // The shop's own advertising, as opposed to `growth`, which is the platform's.
  campaigns: MegaphoneIcon,
};

export function NavIcon({ navKey, ...props }) {
  const Cmp = ICON_MAP[navKey] || GridIcon;
  return <Cmp {...props} />;
}
