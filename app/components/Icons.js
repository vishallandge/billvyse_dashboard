/* =============================================================================
   Icons

   Phosphor Icons, vendored (MIT — Copyright (c) 2023 Phosphor Icons,
   https://github.com/phosphor-icons/core). Path data is copied in rather than
   installed, which keeps this app's zero-icon-dependency policy while giving the
   set geometry drawn by people who draw icons for a living. The previous set was
   hand-plotted on eyeballed coordinates and it showed: mismatched optical sizes,
   two nav rows shipping byte-identical paths, and a gear from 2014.

   TWO WEIGHTS, and the split is deliberate:

     duotone  — every glyph the sidebar, the rail and the quick actions use. Comes
                as two layers: a wash shape carrying className="ic-fill" and the
                glyph itself. The wash is where the shop's accent lives, which is
                what stops thirty outline icons reading as a wireframe.
     regular  — UI chrome: carets, close, trash, sort. A coloured wash on a 13px
                caret in a table header is noise, not design.

   Phosphor draws on a 256 grid as FILLED shapes, not strokes, so there is no
   strokeWidth to tune and no sub-pixel stroke to go blurry at 17px — which was
   the other half of why the old set read as thin and dated.

   Adding an icon: copy the path data out of assets/{duotone,regular}/ in
   @phosphor-icons/core, and on a duotone one give the opacity="0.2" path
   className="ic-fill" instead. See globals.css for what that class does.
   ============================================================================= */

